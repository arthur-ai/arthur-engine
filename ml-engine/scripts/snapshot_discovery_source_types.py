"""Refresh `src/ml_engine/standalone/source_types.json` from the Platform's source types.

The Platform owns each vendor's field schema -- names, descriptions, which are secret,
which are optional -- and renders its source forms from `GET /v1/discovery_source_types`.
A standalone engine has no Platform to ask, so it ships a snapshot of the vendors it has
a connector for, which its control API serves to a dashboard's "Add source" form.

    curl -s -H "Authorization: Bearer $TOKEN" \\
      "$SCOPE/api/v1/discovery_source_types?page_size=100" \\
      | uv run python scripts/snapshot_discovery_source_types.py

Reads that response (or a JSON list or vendor-keyed map of schemas) on stdin. Vendors
this engine has no connector for are left out, and the hand-written entries for vendors
only a standalone engine has (`local`) are kept as they are.
"""

import json
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src" / "ml_engine"))

from discovery import source_connectors  # noqa: E402

SNAPSHOT = (
    Path(__file__).resolve().parents[1]
    / "src"
    / "ml_engine"
    / "standalone"
    / "source_types.json"
)
FIELD_KEYS = (
    "name",
    "is_sensitive",
    "is_optional",
    "d_type",
    "description",
    "allowed_values",
    "priority",
)
SCHEMA_KEYS = (
    "vendor",
    "display_name",
    "source_class",
    "availability",
    "query_language",
)


def schemas(raw: Any) -> list[dict[str, Any]]:
    if isinstance(raw, dict) and "records" in raw:
        return list(raw["records"])
    if isinstance(raw, dict):
        return list(raw.values())
    return list(raw)


def main() -> None:
    current = json.loads(SNAPSHOT.read_text()) if SNAPSHOT.exists() else {}
    platform_vendors = source_connectors().keys()
    snapshot = {
        vendor: entry
        for vendor, entry in current.get("source_types", {}).items()
        if vendor not in platform_vendors
    }
    for schema in schemas(json.load(sys.stdin)):
        if schema["vendor"] not in platform_vendors:
            continue
        entry = {key: schema[key] for key in SCHEMA_KEYS}
        entry["fields"] = sorted(
            ({key: field.get(key) for key in FIELD_KEYS} for field in schema["fields"]),
            key=lambda field: field["priority"],
        )
        snapshot[schema["vendor"]] = entry
    missing = sorted(platform_vendors - snapshot.keys())
    if missing:
        raise SystemExit(f"No schema given for vendor(s): {', '.join(missing)}")
    SNAPSHOT.write_text(
        json.dumps(
            {
                "about": "Generated by scripts/snapshot_discovery_source_types.py "
                "from the Platform's discovery source types; do not edit by hand, "
                "except the entries for vendors only a standalone engine has.",
                "source_types": dict(sorted(snapshot.items())),
            },
            indent=2,
            ensure_ascii=False,
        )
        + "\n",
    )
    print(f"Wrote {len(snapshot)} source type(s) to {SNAPSHOT}")


if __name__ == "__main__":
    main()
