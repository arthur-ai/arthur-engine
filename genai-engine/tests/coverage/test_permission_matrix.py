"""Permission matrix coverage test.

`docs/permission_matrix.txt` lists, per role, every route that role may call.
It is generated by `permission_matrix.py` and committed so that a change to a
permission set, or a new route, shows up as a reviewable diff.

This test fails when:
- a route has neither a permission set (`permission_checker`) nor
  `@public_endpoint`, and is not on the explicit no-auth list; or
- the committed matrix no longer matches the routes (regenerate it with
  `uv run permission_matrix`).
"""

import importlib.util
from pathlib import Path

import pytest

GENAI_ENGINE_DIR = Path(__file__).resolve().parents[2]

_spec = importlib.util.spec_from_file_location(
    "permission_matrix",
    GENAI_ENGINE_DIR / "permission_matrix.py",
)
assert _spec is not None and _spec.loader is not None
permission_matrix = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(permission_matrix)


@pytest.fixture(scope="module")
def routes():
    return permission_matrix.collect_routes()


@pytest.mark.unit_tests
def test_every_route_has_a_permission_set(routes):
    unguarded = permission_matrix.unguarded_routes(routes)
    assert not unguarded, (
        "Routes without a permission set or @public_endpoint:\n"
        + "\n".join(f"  {r.method} {r.path}" for r in unguarded)
    )


@pytest.mark.unit_tests
def test_permission_matrix_is_current(routes):
    expected = permission_matrix.render(routes)
    committed = permission_matrix.MATRIX_PATH.read_text()
    assert committed == expected, (
        f"{permission_matrix.MATRIX_PATH.name} is stale. "
        "Run `uv run permission_matrix` from genai-engine/ and commit the result."
    )
